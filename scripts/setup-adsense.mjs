#!/usr/bin/env node
/**
 * JOSH — AdSense setup helper.
 *
 * Writes adsense-config.js and ads.txt from your real AdSense values, so the
 * publisher ID and ad unit IDs never have to be typed into the HTML by hand.
 *
 * Usage:
 *   node scripts/setup-adsense.mjs --publisher ca-pub-1234567890123456 \
 *     --home-top 1234567890 --home-feed 1234567890 \
 *     --video-below-player 1234567890 --video-sidebar 1234567890 \
 *     --live-top 1234567890 [--auto-ads]
 *
 *   node scripts/setup-adsense.mjs --check   # validate current configuration
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CONFIG_PATH = join(ROOT, 'adsense-config.js');
const ADS_TXT_PATH = join(ROOT, 'ads.txt');

const PUBLISHER_RE = /^ca-pub-(\d{16})$/;
const SLOT_RE = /^\d{6,20}$/;
const GOOGLE_CERT_AUTHORITY = 'f08c47fec0942fa0';

const SLOT_FLAGS = {
  '--home-top': 'homeTop',
  '--home-feed': 'homeFeed',
  '--video-below-player': 'videoBelowPlayer',
  '--video-sidebar': 'videoSidebar',
  '--live-top': 'liveTop'
};

function parseArgs(argv) {
  const out = { publisherId: '', slots: {}, autoAds: false, check: false, errors: [] };

  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--check') {
      out.check = true;
      continue;
    }
    if (arg === '--auto-ads') {
      out.autoAds = true;
      continue;
    }
    if (arg === '--publisher') {
      out.publisherId = String(argv[++i] || '').trim();
      continue;
    }
    if (SLOT_FLAGS[arg]) {
      out.slots[SLOT_FLAGS[arg]] = String(argv[++i] || '').trim();
      continue;
    }
    out.errors.push(`Unknown argument: ${arg}`);
  }

  return out;
}

function validatePublisher(value) {
  const match = PUBLISHER_RE.exec(value);
  if (!match) return { ok: false, message: `Publisher ID must look like ca-pub-################ (16 digits), got "${value}".` };
  return { ok: true, pub16: match[1] };
}

function configSource({ publisherId, slots, autoAds }) {
  return `/**
 * JOSH — Google AdSense configuration (website only, no AdMob).
 *
 * Written by scripts/setup-adsense.mjs. Re-run that script to change the values.
 * Anything left as "" keeps that placement switched off.
 */
window.JOSH_ADSENSE = {
  // Your AdSense publisher ID, e.g. "ca-pub-1234567890123456".
  publisherId: ${JSON.stringify(publisherId)},

  // One numeric ad unit ID per placement. An empty string switches it off.
  slots: {
    homeTop: ${JSON.stringify(slots.homeTop || '')},
    homeFeed: ${JSON.stringify(slots.homeFeed || '')},
    videoBelowPlayer: ${JSON.stringify(slots.videoBelowPlayer || '')},
    videoSidebar: ${JSON.stringify(slots.videoSidebar || '')},
    liveTop: ${JSON.stringify(slots.liveTop || '')}
  },

  // Optional AdSense Auto ads. Off by default so every ad is a deliberate placement.
  enableAutoAds: ${autoAds ? 'true' : 'false'},

  // Set to true to log placement decisions in the browser console.
  debug: false
};
`;
}

function adsTxtSource(pub16) {
  return `# ads.txt — Authorized Digital Sellers for this website
#
# Served from the website root: https://<your-domain>/ads.txt
# Generated by scripts/setup-adsense.mjs from your configured publisher ID.

google.com, pub-${pub16}, DIRECT, ${GOOGLE_CERT_AUTHORITY}
`;
}

function readConfig() {
  if (!existsSync(CONFIG_PATH)) return { publisherId: '', slots: {}, autoAds: false };
  const source = readFileSync(CONFIG_PATH, 'utf8');
  const publisherId = (/publisherId:\s*"([^"]*)"/.exec(source) || [, ''])[1];
  const slots = {};
  const slotBlock = (/slots:\s*\{([\s\S]*?)\}/.exec(source) || [, ''])[1];
  for (const line of slotBlock.split('\n')) {
    const match = /([A-Za-z]+):\s*"([^"]*)"/.exec(line);
    if (match) slots[match[1]] = match[2];
  }
  return { publisherId, slots, autoAds: /enableAutoAds:\s*true/.test(source) };
}

function check() {
  const { publisherId, slots } = readConfig();
  const problems = [];

  if (!publisherId) {
    console.log('adsense-config.js: publisher ID not set yet — all placements stay off (valid state).');
  } else {
    const valid = validatePublisher(publisherId);
    if (!valid.ok) problems.push(valid.message);
    else console.log(`adsense-config.js: publisher ID ${publisherId} is valid.`);
  }

  for (const [name, value] of Object.entries(slots)) {
    if (value && !SLOT_RE.test(value)) problems.push(`Ad unit ID for ${name} is invalid: "${value}".`);
  }
  const configured = Object.entries(slots).filter(([, value]) => value);
  console.log(`adsense-config.js: ${configured.length} ad unit ID(s) configured${configured.length ? ` (${configured.map(([n]) => n).join(', ')})` : ''}.`);

  if (!existsSync(ADS_TXT_PATH)) {
    problems.push('ads.txt is missing from the website root.');
  } else {
    const adsTxt = readFileSync(ADS_TXT_PATH, 'utf8');
    const active = adsTxt.split('\n').filter((line) => line.trim() && !line.trim().startsWith('#'));
    const pubMatch = PUBLISHER_RE.exec(publisherId);
    if (pubMatch) {
      const expected = `google.com, pub-${pubMatch[1]}, DIRECT, ${GOOGLE_CERT_AUTHORITY}`;
      if (!active.includes(expected)) problems.push(`ads.txt does not contain: ${expected} (run this script with --publisher to write it).`);
      else console.log('ads.txt: authorised seller line matches the configured publisher ID.');
    } else if (active.length) {
      problems.push('ads.txt declares a seller line while no publisher ID is configured.');
    } else {
      console.log('ads.txt: present at the website root, no seller declared yet (valid state).');
    }
  }

  if (problems.length) {
    console.error('\nProblems found:');
    for (const problem of problems) console.error(` - ${problem}`);
    process.exitCode = 1;
    return;
  }
  console.log('\nConfiguration looks consistent.');
}

function write(args) {
  const valid = validatePublisher(args.publisherId);
  if (!valid.ok) {
    console.error(valid.message);
    process.exitCode = 1;
    return;
  }

  for (const [name, value] of Object.entries(args.slots)) {
    if (value && !SLOT_RE.test(value)) {
      console.error(`Ad unit ID for ${name} must be numeric (6-20 digits), got "${value}".`);
      process.exitCode = 1;
      return;
    }
  }

  writeFileSync(CONFIG_PATH, configSource(args), 'utf8');
  writeFileSync(ADS_TXT_PATH, adsTxtSource(valid.pub16), 'utf8');

  const configured = Object.entries(args.slots).filter(([, value]) => value);
  console.log(`Updated adsense-config.js with publisher ${args.publisherId}.`);
  console.log(`Updated ads.txt with: google.com, pub-${valid.pub16}, DIRECT, ${GOOGLE_CERT_AUTHORITY}`);
  console.log(configured.length
    ? `Ad units configured: ${configured.map(([name, value]) => `${name}=${value}`).join(', ')}`
    : 'No ad unit IDs given — placements stay hidden until you add them.');
  console.log('\nNext: reload the site and confirm no layout change until AdSense serves an ad.');
}

const args = parseArgs(process.argv.slice(2));
if (args.errors.length) {
  for (const error of args.errors) console.error(error);
  process.exitCode = 1;
} else if (args.check) {
  check();
} else if (!args.publisherId) {
  console.log('JOSH AdSense setup\n');
  console.log('  node scripts/setup-adsense.mjs --publisher ca-pub-################ \\');
  console.log('    --home-top <unit id> --home-feed <unit id> \\');
  console.log('    --video-below-player <unit id> --video-sidebar <unit id> --live-top <unit id>');
  console.log('\n  node scripts/setup-adsense.mjs --check');
  console.log('\nSee README-ADSENSE.md for the full checklist.');
} else {
  write(args);
}
